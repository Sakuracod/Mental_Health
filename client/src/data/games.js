export function getGameBySlug(slug) {
  return GAMES.find(g => g.slug === slug)
}

export const GAME_CATEGORIES = [...new Set(GAMES.map(g => g.category))]

const GUIDE_KEY_PREFIX = 'game_guide_seen_'

export function hasSeenGuide(slug) {
  return localStorage.getItem(GUIDE_KEY_PREFIX + slug) === '1'
}

export function markGuideSeen(slug) {
  localStorage.setItem(GUIDE_KEY_PREFIX + slug, '1')
}
